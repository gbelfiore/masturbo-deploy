export function isLocale(value: string): value is Locale {
  return LOCALES.some((item) => item.id === value);
}

export function loadLocale(context: vscode.ExtensionContext): Locale {
  const saved = context.globalState.get<string>(LANG_KEY, "en");
  return isLocale(saved) ? saved : "en";
}

export async function saveLocale(context: vscode.ExtensionContext, locale: Locale): Promise<void> {
  await context.globalState.update(LANG_KEY, locale);
}

export function t(locale: Locale, key: string, vars?: Record<string, string>): string {
  let text = MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}
